const POSTAL = new Set(Object.values(STATE_NAMES));

/** Accept "FL" or "Florida". Returns null when it is not a US state or DC. */
export function normalizeUsState(raw: string): string | null {
  const trimmed = raw.trim().replace(/\s+/g, " ");
  if (!trimmed) return null;
  if (trimmed.length === 2) {
    const code = trimmed.toUpperCase();
    return POSTAL.has(code) ? code : null;
  }
  return STATE_NAMES[trimmed.toLowerCase()] ?? null;
}
